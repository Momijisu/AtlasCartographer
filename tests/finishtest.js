const { chromium } = require('playwright');
const { device, waitSynced, stroke } = require('./mock.js');
let CAT = null;
(async () => {
  const browser = await chromium.launch();
  const A = await device(browser, 'A');
  await waitSynced(A);
  await A.goto('http://localhost:8765/#/library');
  await A.setInputFiles('#pickFolder', 'pack/Fantasy Stamps');
  await A.waitForSelector('.modal input[name=pack]'); await A.click('.modal button.primary');
  await A.waitForSelector('.pack-row', { timeout: 20000 });
  await A.goto('http://localhost:8765/#/');
  await A.click('#newProject'); await A.fill('input[name=name]', 'Finish'); await A.click('.modal button.primary');
  await A.waitForSelector('.editor-canvas');
  await A.click('[data-tool=land]');
  await A.$eval('.land-size', (r) => { r.value = 90; r.dispatchEvent(new Event('input')); });
  await stroke(A, [[300, 250], [600, 260], [850, 350], [800, 550], [450, 560], [320, 420], [400, 380], [650, 420]]);
  await A.click('[data-act=style]');
  await A.selectOption('.style-panel select[name=grid]', 'hex');
  await A.waitForSelector('.style-panel input[name=gridSize]');
  await A.selectOption('.style-panel select[name=frame]', 'double');
  await A.$eval('.style-panel input[name=vignette]', (r) => { r.value = 0.6; r.dispatchEvent(new Event('change', { bubbles: true })); });
  await A.click('.style-panel [data-paper]');
  await A.waitForSelector('.picker:not([hidden]) .pk-browse .tile');
  CAT = 'Textures';
  await A.waitForSelector('.pk-browse .tile'); await A.click('.pk-browse .tile[aria-label="Ground"]');
  await A.click('.picker [data-close]');
  await A.click('[data-tool=text]'); await A.mouse.click(580, 400);
  await A.fill('.label-form input[name=text]', 'Hexmoor'); await A.click('.label-form button.primary');
  await A.waitForTimeout(600);
  await A.screenshot({ path: 'finish.png' });
  console.log(JSON.stringify(await A.evaluate(async () => { const s = await import('./js/store.js'); const id = location.hash.split('/p/')[1]; const st = (await s.getDoc(id)).objects.style; return [st.grid, st.frame, st.vignette, !!st.overlay]; })));
  await browser.close();
})().catch((e) => { console.error('FAIL', e); process.exit(1); });
