const { chromium } = require('playwright');
const { device, waitSynced, stroke } = require('./mock.js');
(async () => {
  const browser = await chromium.launch();
  const A = await device(browser, 'A');
  await waitSynced(A);
  await A.click('#newProject'); await A.fill('input[name=name]', 'Labels'); await A.click('.modal button.primary');
  await A.waitForSelector('.editor-canvas');
  await A.click('[data-tool=land]');
  await A.$eval('.land-size', (r) => { r.value = 75; r.dispatchEvent(new Event('input')); });
  await stroke(A, [[300, 250], [600, 280], [850, 350], [800, 550], [450, 520], [320, 420], [330, 300], [600, 400]]);
  await A.click('[data-tool=text]');
  await A.mouse.click(600, 380);
  await A.waitForSelector('.label-form');
  await A.fill('.label-form input[name=text]', 'The Shattered Coast');
  await A.$eval('.label-form input[name=curve]', (r) => { r.value = 30; r.dispatchEvent(new Event('input', { bubbles: true })); });
  await A.check('.label-form input[name=caps]');
  await A.screenshot({ path: 'label-dialog.png' });
  await A.click('.label-form button.primary');
  await A.mouse.click(400, 650);
  await A.fill('.label-form input[name=text]', 'Sea of Glass');
  await A.selectOption('.label-form select[name=font]', 'italic');
  await A.$eval('.label-form input[name=curve]', (r) => { r.value = -25; r.dispatchEvent(new Event('input', { bubbles: true })); });
  await A.click('.label-form button.primary');
  await A.waitForTimeout(300);
  // select the first label and rotate it a little, then edit via Enter
  await A.click('[data-tool=select]');
  await A.mouse.click(600, 375);
  console.log('edit button visible:', await A.$eval('[data-act="edit-text"]', (b) => !b.hidden && !b.disabled));
  await A.screenshot({ path: 'labels.png' });
  await A.keyboard.press('Enter');
  await A.waitForSelector('.label-form');
  console.log('editing:', await A.$eval('.label-form input[name=text]', (i) => i.value));
  await A.fill('.label-form input[name=size]', '160');
  await A.click('.label-form button.primary');
  await A.waitForTimeout(300);
  await A.screenshot({ path: 'labels2.png' });
  const objs = await A.evaluate(async () => { const s = await import('./js/store.js'); const id = location.hash.split('/p/')[1]; return s.liveObjects(await s.getDoc(id)).filter((o) => o.kind === 'label').map((o) => [o.text, o.size, o.font, o.curve]); });
  console.log(JSON.stringify(objs));
  await browser.close();
})().catch((e) => { console.error('FAIL', e); process.exit(1); });
