const { chromium } = require('playwright');
const { device, waitSynced, stroke } = require('./mock.js');
let CAT = null;
(async () => {
  const browser = await chromium.launch();
  const A = await device(browser, 'A');
  await waitSynced(A);
  await A.goto('http://localhost:8765/#/library');
  await A.setInputFiles('#pickFolder', 'pack/Fantasy Stamps');
  await A.waitForSelector('.modal input[name=pack]'); await A.click('.modal button.primary');
  await A.waitForSelector('.pack-row', { timeout: 20000 });
  await A.goto('http://localhost:8765/#/');
  await A.click('#newProject'); await A.fill('input[name=name]', 'Terrain'); await A.click('.modal button.primary');
  await A.waitForSelector('.editor-canvas');
  await A.click('[data-tool=land]');
  await A.$eval('.land-size', (r) => { r.value = 85; r.dispatchEvent(new Event('input')); });
  await stroke(A, [[300, 250], [600, 260], [850, 350], [800, 550], [450, 560], [320, 420], [400, 380], [650, 420]]);
  await A.click('[data-tool=terrain]');
  await A.click('[data-act=terrain-picker]');
  await A.waitForSelector('.picker:not([hidden]) .pk-browse');
  console.log('texture cats:', await A.$$eval('.pk-cat option', (o) => o.map((x) => x.value)));
  CAT = 'Textures';
  await A.waitForSelector('.pk-browse .tile');
  await A.click(`${CAT ? `.pk-section:has(.pk-cat-name:text-is("${CAT}")) ` : '.pk-browse '}.tile >> nth=0`);
  await A.click('[data-act=terrain-picker]');
  await A.$eval('.terrain-size', (r) => { r.value = 60; r.dispatchEvent(new Event('input')); });
  await stroke(A, [[350, 300], [500, 330], [700, 300], [950, 280]]); // runs off the coast: should clip
  CAT = null; await A.click('[data-tool=stamp]'); await A.waitForSelector('.pk-browse .tile'); await A.click(`${CAT ? `.pk-section:has(.pk-cat-name:text-is("${CAT}")) ` : '.pk-browse '}.tile >> nth=0`);
  await A.mouse.click(560, 470); await A.mouse.click(640, 480);
  await A.click('[data-act=style]');
  await A.waitForSelector('.style-panel:not([hidden])');
  await A.check('.style-panel input[name=stampShadow]');
  await A.$eval('.style-panel input[name=coastWidth]', (r) => { r.value = 12; r.dispatchEvent(new Event('change', { bubbles: true })); });
  await A.$eval('.style-panel input[name=sea]', (r) => { r.value = '#8fb3c4'; r.dispatchEvent(new Event('change', { bubbles: true })); });
  await A.waitForTimeout(600);
  await A.screenshot({ path: 'terrain.png' });
  const style = await A.evaluate(async () => { const s = await import('./js/store.js'); const id = location.hash.split('/p/')[1]; const d = await s.getDoc(id); return [d.objects.style, s.liveObjects(d).filter((o) => o.kind === 'terrain').length]; });
  console.log(JSON.stringify(style));
  await A.keyboard.press('Control+z');
  await A.waitForTimeout(300);
  console.log('after undo sea:', await A.evaluate(async () => { const s = await import('./js/store.js'); const id = location.hash.split('/p/')[1]; return (await s.getDoc(id)).objects.style.sea; }));
  await browser.close();
})().catch((e) => { console.error('FAIL', e); process.exit(1); });
